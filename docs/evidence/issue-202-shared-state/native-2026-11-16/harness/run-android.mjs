import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=process.argv[2], name=process.argv[3];
if(!/^[a-z0-9-]+$/.test(name))throw Error('Invalid case name');
const config=JSON.parse(fs.readFileSync(path.join(root,'e2e-private/config.json'),'utf8').replace(/^\uFEFF/,''));
const result=path.join(root,'e2e-results',name);fs.mkdirSync(result,{recursive:true});
const raw=path.join(root,'e2e-private',name);fs.mkdirSync(raw,{recursive:true});
const tools=path.join(process.env.LOCALAPPDATA,'CoffeeShopMobileTools');
const java='C:/Program Files/Eclipse Adoptium/jdk-17.0.17.10-hotspot/bin/java.exe';
const adb=path.join(process.env.LOCALAPPDATA,'Android/Sdk/platform-tools/adb.exe');
const env={...process.env,MAESTRO_STAFF_USERNAME:config.mobile,MAESTRO_STAFF_PASSWORD:config.password,MAESTRO_INGREDIENT:'I202 Shared Beans',MAESTRO_CLI_NO_ANALYTICS:'true',MAESTRO_CLI_ANALYSIS_NOTIFICATION_DISABLED:'true'};
const flow=path.join(root,'e2e-flows',name+'.yaml');
const r=spawnSync(java,['--enable-native-access=ALL-UNNAMED','-Xmx1024m','-cp',path.join(tools,'maestro-2.12.1/maestro/lib/*'),'maestro.cli.AppKt','--device','emulator-5554','test','--format','junit','--output',path.join(result,'junit.xml'),'--debug-output',raw,flow],{env,cwd:root,encoding:'utf8',timeout:180000,maxBuffer:4*1024*1024});
fs.writeFileSync(path.join(raw,'console.log'),(r.stdout??'')+(r.stderr??''));
const shot=spawnSync(adb,['-s','emulator-5554','exec-out','screencap','-p'],{maxBuffer:16*1024*1024});if(shot.status===0)fs.writeFileSync(path.join(result,'screen.png'),shot.stdout);
const xml=fs.existsSync(path.join(result,'junit.xml'))?fs.readFileSync(path.join(result,'junit.xml'),'utf8'):'';
const passed=r.status===0 && /tests="1"/.test(xml)&&/failures="0"/.test(xml)&&!/skipped="[1-9]/.test(xml);
fs.writeFileSync(path.join(result,'result.json'),JSON.stringify({name,passed,exitCode:r.status,at:new Date().toISOString(),error:r.error?.code??null},null,2));
console.log(JSON.stringify({name,passed,exitCode:r.status,error:r.error?.code??null}));
process.exitCode=passed?0:1;
